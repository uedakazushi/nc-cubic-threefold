#!/usr/bin/env python3
"""Exact tangent certificate for the algebraic Jacobian moduli chart.

Reuses the polynomial operations and the input point in the existing Rat113
certificate. Checks the actual GL5-orbit plus the thirteen-parameter slice,
including its scalar kernel, inside the full Poisson equation tangent space.
Only nonzero modular minors are used as characteristic-zero rank witnesses;
equations and kernel identities are checked over Z.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        default=Path("build/jacobian_etale_point.json"))
    args = parser.parse_args()
    helper_path = HERE / "verify_rat113_tangent.py"
    input_path = HERE / "rat113_tangent_certificate.json"
    spec = importlib.util.spec_from_file_location("rat113_polynomials", helper_path)
    rat = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(rat)
    old = json.loads(input_path.read_text())
    assert hashlib.sha256(helper_path.read_bytes()).hexdigest() == old["source_sha256"]
    terms = {tuple(t["exponents"]): t["coefficient"]
             for t in old["active_polynomial_terms"]}
    variables = [{e: 1} for e in rat.MON1]
    x, y, z, u, v = variables
    p = rat.jacobian(terms, u, v)

    def power(f, n):
        out = {rat.ZERO: 1}
        for _ in range(n):
            out = rat.mul(out, f)
        return out

    slice_polynomials = [
        rat.add(power(x, 3), power(y, 3), power(z, 3)),
        rat.mul(rat.mul(x, y), z),
        rat.mul(v, power(y, 2)),
        rat.mul(rat.add(u, v), power(z, 2)),
    ]
    binary_quadrics = [power(u, 2), rat.mul(u, v), power(v, 2)]
    slice_polynomials += [rat.mul(active, quadratic)
                          for active in (x, y, z)
                          for quadratic in binary_quadrics]
    assert len(slice_polynomials) == 13
    parameters = [3, 5, 2, 3, 1, 1, 2, 2, 3, 1, 1, 4, 5]
    assert terms == rat.add(
        rat.mul(u, power(x, 2)),
        *(rat.scale(f, c) for f, c in zip(slice_polynomials, parameters))
    )

    # g·p = Sym²(g) p (wedge²(g))^-1. E_ab sends variable b to a.
    orbit = []
    for a in range(5):
        for b in range(5):
            q = {}
            for i, j in rat.PAIRS:
                value = rat.mul(variables[a], rat.der(rat.entry(p, i, j), b))
                if i == b:
                    value = rat.add(value, rat.scale(rat.entry(p, a, j), -1))
                if j == b:
                    value = rat.add(value, rat.scale(rat.entry(p, i, a), -1))
                q[i, j] = value
            orbit.append(rat.vector(q))
    slice_columns = [rat.vector(rat.jacobian(f, u, v)) for f in slice_polynomials]
    columns = orbit + slice_columns
    differential = rat.transpose(columns)
    assert (len(differential), len(differential[0])) == (150, 38)
    assert all(sum(orbit[6*i][j] for i in range(5)) == 0 for j in range(150))

    equations = rat.transpose([
        rat.differential(p, {ij: {e: 1}}) for ij, e in rat.COLUMNS
    ])
    assert all(c == 0 for c in rat.differential(p, p))
    assert all(sum(a*b for a, b in zip(row, col)) == 0
               for row in equations for col in columns)
    equation_minor = rat.minor_witness(equations, 1000003)
    chart_minor = rat.minor_witness(differential, 1000003)
    assert equation_minor == old["equation_differential"]
    assert equation_minor["size"] == 113
    assert chart_minor["size"] == 37
    # Rank <=37 also follows directly from the exact scalar kernel.
    # Rank equations >=113 and equations*differential=0 make both ranks exact.

    a, b = 3, 5
    pp, qq, rr = 2-b, -(2+b), -6*a
    factors = {
        "smooth_top": a*(27*a**3+b**3),
        "pqr": pp*qq*rr,
        "smooth_point_curve": (pp**3+qq**3+rr**3)**3-27*pp**3*qq**3*rr**3,
        "p3_minus_q3": pp**3-qq**3,
        "q3_minus_r3": qq**3-rr**3,
        "r3_minus_p3": rr**3-pp**3,
        "third_iterate_factor": pp**6+qq**6+rr**6-pp**3*qq**3-qq**3*rr**3-rr**3*pp**3,
    }
    assert all(factors.values())
    certificate = {
        "date": "2026-11-19", "version": 1,
        "input_point": "active_polynomial_terms in rat113_tangent_certificate.json",
        "parameters": {"a": 3, "b": 5, "alpha": 2, "beta": 3,
                       "m": [[1, 1, 2], [2, 3, 1], [1, 4, 5]]},
        "delta_factor_values": factors,
        "chart_matrix_shape": [150, 38],
        "chart_columns": "E_ab in row-major order (a,b=0..4), then a,b,alpha,beta,m10,m11,m12,m20,m21,m22,m30,m31,m32",
        "chart_minor": chart_minor,
        "chart_rank_over_Q": 37,
        "kernel": "one-dimensional, generated by the sum of the five diagonal GL5 columns",
        "equation_minor_reference": "rat113_tangent_certificate.json:equation_differential",
        "equation_minor_recomputed_and_matches": True,
        "equation_rank_over_Q": 113,
        "equations_times_chart_exact_zero": True,
        "poisson_equations_exact_zero": True,
        "consequence": "The PGL5 action-plus-slice differential is an isomorphism at the displayed smooth point of Q113, and this point lies in Delta!=0.",
        "scope": "Certifies the finite tangent and nonvanishing inputs. Stack descent, universal centers, Abelian equivalence and categorical smoothness are not numerical conclusions.",
        "helper_sha256": hashlib.sha256(helper_path.read_bytes()).hexdigest(),
        "input_sha256": hashlib.sha256(input_path.read_bytes()).hexdigest(),
        "source_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(certificate, indent=2)+"\n")
    print(json.dumps({"status": "pass", "chart_rank_Q": 37,
                      "equation_rank_Q": 113,
                      "chart_minor_mod_1000003": chart_minor["determinant_mod_prime"],
                      "scalar_kernel_exact": True, "equations_times_chart_exact_zero": True,
                      "delta_nonzero": True, "output": str(args.output)}, indent=2))


if __name__ == "__main__":
    main()
